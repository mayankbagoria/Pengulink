"""tests.e2e.test_connectivity_report_e2e
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
End-to-End integration test suite for KDE Connect Connectivity Report plugin.
Executes over live loopback mTLS sockets between PenguLinkDaemon and MockKdeConnectDevice.

Covers:
- test_e2e_cr_001_capability_negotiation: Identity handshake and capability advertisement
- test_e2e_cr_002_push_report_and_query: Push reception, event delivery, and JSON-RPC query
- test_e2e_cr_003_on_demand_query: On-demand query polling (request -> mock auto-reply)
- test_e2e_cr_004_multi_sim_report: Multi-SIM report processing with distinct radio types and bars
- test_e2e_cr_005_multi_device_isolation: Concurrent devices with non-interfering reports
- test_e2e_cr_006_malformed_packet_resilience: In-stream malformed packets handled safely
- test_e2e_cr_007_reconnection_state_preservation: Cache retained across disconnect and updated on reconnect
- test_e2e_cr_008_unpair_cache_cleanup: Device unpairing purges connectivity cache immediately
"""

from __future__ import annotations

import asyncio
import json
import uuid
from pathlib import Path
from typing import Any, Dict, List

import pytest

from pengulink.core.events import (
    ConnectivityReportReceived,
    DeviceConnected,
    DeviceDisconnected,
    PingReceived,
)
from pengulink.core.exceptions import IPCError
from pengulink.daemon.service import PenguLinkDaemon
from pengulink.network.packet import Packet
from tests.e2e.conftest import e2e_environment, wait_for
from tests.mock.mock_device import MockDevice, MockDeviceConfig


async def _pair_and_connect(daemon: PenguLinkDaemon, mock: MockDevice) -> None:
    """Helper to establish mutual pairing and an active TLS connection."""
    await mock.broadcast_identity(
        target_ip="127.0.0.1",
        target_port=daemon.config.network.udp_port,
    )
    await wait_for(lambda: mock.device_id in daemon._discovered_devices, timeout=4.0)
    res = await daemon.pair_device(mock.device_id, wait=True, timeout=5.0)
    assert res["paired"] is True
    assert daemon.is_device_connected(mock.device_id) is True


async def test_e2e_cr_001_capability_negotiation(tmp_path: Path) -> None:
    """Verify bidirectional capability advertisement during identity handshake.

    1. Mock broadcasts UDP identity announcing outgoing 'kdeconnect.connectivity_report'
       and incoming 'kdeconnect.connectivity_report.request'.
    2. Daemon ingests broadcast into DiscoveredDevice records.
    3. Daemon advertises incoming 'kdeconnect.connectivity_report' and outgoing
       'kdeconnect.connectivity_report.request' via cleartext TCP identity preamble.
    """
    async with e2e_environment(tmp_path) as (daemon, mock, ipc_client):
        # 1. Mock broadcasts identity
        await mock.broadcast_identity(
            target_ip="127.0.0.1",
            target_port=daemon.config.network.udp_port,
        )

        await wait_for(
            lambda: mock.device_id in daemon._discovered_devices,
            timeout=4.0,
            desc="daemon discovering mock device",
        )

        # 2. Check capabilities stored in daemon's discovered device record
        discovered = daemon._discovered_devices[mock.device_id]
        assert "kdeconnect.connectivity_report" in discovered.outgoing_capabilities
        assert "kdeconnect.connectivity_report.request" in discovered.incoming_capabilities

        # 3. Check daemon's own advertised capabilities
        incoming_caps = daemon.plugin_registry.get_all_incoming_capabilities()
        outgoing_caps = daemon.plugin_registry.get_all_outgoing_capabilities()
        assert "kdeconnect.connectivity_report" in incoming_caps
        assert "kdeconnect.connectivity_report.request" in outgoing_caps

        # 4. Verify TCP cleartext preamble generated by daemon reflects capabilities
        preamble_bytes = daemon.tcp_manager._build_cleartext_identity()
        preamble_data = json.loads(preamble_bytes.decode("utf-8").strip())
        assert "kdeconnect.connectivity_report" in preamble_data["body"]["incomingCapabilities"]
        assert "kdeconnect.connectivity_report.request" in preamble_data["body"]["outgoingCapabilities"]


async def test_e2e_cr_002_push_report_and_query(tmp_path: Path) -> None:
    """Verify live mobile-to-desktop push report reception, event delivery, and JSON-RPC query.

    1. Mock pairs and connects over TLS with PenguLink daemon.
    2. Mock sends unsolicited push kdeconnect.connectivity_report packet (Single SIM 5G).
    3. ConnectivityReportReceived event is emitted on EventBus.
    4. Daemon caches report in ConnectivityReportPlugin.
    5. JSON-RPC get_connectivity_report IPC query returns populated report.
    """
    cr_events: List[ConnectivityReportReceived] = []

    async with e2e_environment(tmp_path) as (daemon, mock, ipc_client):
        await _pair_and_connect(daemon, mock)

        daemon.event_bus.subscribe(
            ConnectivityReportReceived,
            lambda ev: cr_events.append(ev),
        )

        # Transmit push report from mock
        await mock.send_connectivity_report({
            "0": {
                "networkType": "5G",
                "signalStrength": 4,
            }
        })

        # Wait for EventBus delivery
        await wait_for(
            lambda: len(cr_events) > 0,
            timeout=4.0,
            desc="ConnectivityReportReceived event delivery",
        )

        ev = cr_events[0]
        assert ev.device_id == mock.device_id
        assert "0" in ev.signal_strengths
        assert ev.signal_strengths["0"]["network_type"] == "5G"
        assert ev.signal_strengths["0"]["signal_strength"] == 4

        # Verify internal plugin cache
        cached = daemon.connectivity_plugin.get_device_report(mock.device_id)
        assert cached is not None
        assert cached.device_id == mock.device_id
        assert "0" in cached.signal_strengths
        assert cached.signal_strengths["0"].network_type == "5G"
        assert cached.signal_strengths["0"].signal_strength == 4

        # Verify JSON-RPC IPC query
        report = await ipc_client.get_connectivity_report(mock.device_id)
        assert report is not None
        assert report["device_id"] == mock.device_id
        assert "0" in report["signal_strengths"]
        assert report["signal_strengths"]["0"]["network_type"] == "5G"
        assert report["signal_strengths"]["0"]["signal_strength"] == 4
        assert report["timestamp"] > 0


async def test_e2e_cr_003_on_demand_query(tmp_path: Path) -> None:
    """Verify on-demand polling query (request_connectivity_report -> Mock auto-reply).

    1. Mock connected with auto_connectivity_reply=True.
    2. Daemon sends request_connectivity_report via JSON-RPC.
    3. Mock receives kdeconnect.connectivity_report.request and auto-replies.
    4. Daemon receives reply, emits event, and updates cache.
    """
    cr_events: List[ConnectivityReportReceived] = []

    async with e2e_environment(tmp_path, auto_connectivity_reply=True) as (daemon, mock, ipc_client):
        await _pair_and_connect(daemon, mock)

        daemon.event_bus.subscribe(
            ConnectivityReportReceived,
            lambda ev: cr_events.append(ev),
        )

        # Initially no report is cached
        assert daemon.connectivity_plugin.get_device_report(mock.device_id) is None

        # Issue on-demand query via IPC
        res = await ipc_client.request_connectivity_report(mock.device_id)
        assert res["success"] is True
        assert res["device_id"] == mock.device_id

        # Verify mock received the request packet
        await wait_for(
            lambda: len(mock.get_received_packets("kdeconnect.connectivity_report.request")) > 0,
            timeout=4.0,
            desc="mock receiving connectivity request",
        )

        # Verify daemon received the auto-reply from mock
        await wait_for(
            lambda: len(cr_events) > 0,
            timeout=4.0,
            desc="daemon receiving connectivity auto-reply",
        )

        # Verify report is accessible via IPC
        report = await ipc_client.get_connectivity_report(mock.device_id)
        assert report is not None
        assert report["device_id"] == mock.device_id
        assert "0" in report["signal_strengths"]


async def test_e2e_cr_004_multi_sim_report(tmp_path: Path) -> None:
    """Verify processing multi-SIM report with distinct radio generations and signal strengths.

    1. Mock sends multi-SIM report with SIM 1 (5G / 4 bars), SIM 2 (LTE / 2 bars),
       and SIM 3 (3G / 1 bar).
    2. Daemon parses all subscriptions accurately.
    3. IPC query retrieves all subscriptions with correct fields and types.
    """
    async with e2e_environment(tmp_path) as (daemon, mock, ipc_client):
        await _pair_and_connect(daemon, mock)

        multi_sim_payload = {
            "0": {"networkType": "5G", "signalStrength": 4},
            "1": {"networkType": "LTE", "signalStrength": 2},
            "2": {"networkType": "3G", "signalStrength": 1},
        }

        await mock.send_connectivity_report(multi_sim_payload)

        def _check_multi_sim() -> bool:
            rep = daemon.connectivity_plugin.get_device_report(mock.device_id)
            return bool(rep and len(rep.signal_strengths) == 3)

        await wait_for(
            _check_multi_sim,
            timeout=4.0,
            desc="daemon caching multi-SIM report",
        )

        report = await ipc_client.get_connectivity_report(mock.device_id)
        assert report is not None
        sims = report["signal_strengths"]
        assert len(sims) == 3

        assert sims["0"]["network_type"] == "5G"
        assert sims["0"]["signal_strength"] == 4
        assert sims["1"]["network_type"] == "LTE"
        assert sims["1"]["signal_strength"] == 2
        assert sims["2"]["network_type"] == "3G"
        assert sims["2"]["signal_strength"] == 1


async def test_e2e_cr_005_multi_device_isolation(tmp_path: Path) -> None:
    """Verify two mock devices connected simultaneously do not cross-contaminate reports.

    1. Provision two mock devices (mock_a and mock_b).
    2. Connect and pair both devices to daemon.
    3. mock_a sends 5G / 4 bars.
    4. mock_b sends LTE / 1 bar.
    5. Verify reports are isolated per device_id and do not leak between devices.
    """
    async with e2e_environment(tmp_path) as (daemon, mock_a, ipc_client):
        # Create second independent mock device
        m_cfg_b = MockDeviceConfig(
            device_id=f"mock_device_b_{uuid.uuid4().hex[:12]}",
            device_name="Mock Android Phone B",
            auto_pair=True,
        )
        mock_b = MockDevice(config=m_cfg_b)
        await mock_b.start(listen_tcp=True, port=0)

        try:
            await _pair_and_connect(daemon, mock_a)
            await _pair_and_connect(daemon, mock_b)

            # mock_a transmits 5G
            await mock_a.send_connectivity_report({
                "0": {"networkType": "5G", "signalStrength": 4}
            })

            # mock_b transmits LTE on slot "sim_secondary"
            await mock_b.send_connectivity_report({
                "sim_secondary": {"networkType": "LTE", "signalStrength": 1}
            })

            # Wait for both reports to be cached
            await wait_for(
                lambda: daemon.connectivity_plugin.get_device_report(mock_a.device_id) is not None
                and daemon.connectivity_plugin.get_device_report(mock_b.device_id) is not None,
                timeout=4.0,
                desc="caching reports for both devices",
            )

            rep_a = await ipc_client.get_connectivity_report(mock_a.device_id)
            rep_b = await ipc_client.get_connectivity_report(mock_b.device_id)

            assert rep_a is not None
            assert rep_b is not None

            # Assert isolation
            assert rep_a["device_id"] == mock_a.device_id
            assert "0" in rep_a["signal_strengths"]
            assert "sim_secondary" not in rep_a["signal_strengths"]
            assert rep_a["signal_strengths"]["0"]["network_type"] == "5G"
            assert rep_a["signal_strengths"]["0"]["signal_strength"] == 4

            assert rep_b["device_id"] == mock_b.device_id
            assert "sim_secondary" in rep_b["signal_strengths"]
            assert "0" not in rep_b["signal_strengths"]
            assert rep_b["signal_strengths"]["sim_secondary"]["network_type"] == "LTE"
            assert rep_b["signal_strengths"]["sim_secondary"]["signal_strength"] == 1

        finally:
            await mock_b.stop()


async def test_e2e_cr_006_malformed_packet_resilience(tmp_path: Path) -> None:
    """Verify malformed connectivity packets over live TLS do not crash or drop connection.

    1. Mock sends a series of malformed connectivity packets:
       - non-dict body
       - null signalStrengths
       - non-dict signalStrengths
       - invalid types inside signal object
    2. Connection remains alive.
    3. Subsequent valid ping and valid report are processed successfully.
    """
    ping_events: List[PingReceived] = []

    async with e2e_environment(tmp_path) as (daemon, mock, ipc_client):
        await _pair_and_connect(daemon, mock)

        daemon.event_bus.subscribe(
            PingReceived,
            lambda ev: ping_events.append(ev),
        )

        # 1. Send malformed packets over live TLS wire
        raw_malformed = [
            b'{"id": 1, "type": "kdeconnect.connectivity_report", "body": "string_not_dict"}\n',
            b'{"id": 2, "type": "kdeconnect.connectivity_report"}\n',
            b'{"id": 3, "type": "kdeconnect.connectivity_report", "body": null}\n',
            b'{"id": 4, "type": "kdeconnect.connectivity_report", "body": {"signalStrengths": null}}\n',
            b'{"id": 5, "type": "kdeconnect.connectivity_report", "body": {"signalStrengths": [1, 2, 3]}}\n',
            b'{"id": 6, "type": "kdeconnect.connectivity_report", "body": {"signalStrengths": {"0": {"networkType": 99999, "signalStrength": "corrupt_data"}}}}\n',
        ]

        assert mock.active_connection is not None
        for raw in raw_malformed:
            await mock.active_connection.write_line(raw)
            await asyncio.sleep(0.02)

        # 2. Connection must remain healthy
        assert daemon.is_device_connected(mock.device_id) is True
        assert mock.active_connection is not None and not mock.active_connection.is_closed

        # 3. Follow up with valid ping to prove channel integrity
        await mock.send_ping(message="Ping after malformed connectivity packets")
        await wait_for(
            lambda: len(ping_events) > 0,
            timeout=3.0,
            desc="ping received after malformed packets",
        )
        assert ping_events[0].message == "Ping after malformed connectivity packets"

        # 4. Follow up with valid connectivity report
        await mock.send_connectivity_report({
            "0": {"networkType": "5G", "signalStrength": 4}
        })
        await wait_for(
            lambda: daemon.connectivity_plugin.get_device_report(mock.device_id) is not None,
            timeout=3.0,
            desc="valid connectivity report processed after malformed packets",
        )
        report = await ipc_client.get_connectivity_report(mock.device_id)
        assert report is not None
        assert report["signal_strengths"]["0"]["network_type"] == "5G"


async def test_e2e_cr_007_reconnection_state_preservation(tmp_path: Path) -> None:
    """Verify connectivity cache preservation across disconnect and update across reconnect.

    1. Mock sends initial report (5G / 4 bars).
    2. Mock drops connection.
    3. Cached report is preserved in daemon during disconnection.
    4. Mock reconnects without re-pairing using pinned mTLS certificate.
    5. Mock sends updated report (LTE / 2 bars).
    6. Daemon updates cache seamlessly.
    """
    connect_events: List[DeviceConnected] = []
    disconnect_events: List[DeviceDisconnected] = []

    async with e2e_environment(tmp_path) as (daemon, mock, ipc_client):
        await _pair_and_connect(daemon, mock)

        daemon.event_bus.subscribe(DeviceConnected, lambda ev: connect_events.append(ev))
        daemon.event_bus.subscribe(DeviceDisconnected, lambda ev: disconnect_events.append(ev))

        # 1. Send initial report
        await mock.send_connectivity_report({
            "0": {"networkType": "5G", "signalStrength": 4}
        })
        await wait_for(
            lambda: daemon.connectivity_plugin.get_device_report(mock.device_id) is not None,
            timeout=3.0,
        )

        # 2. Drop connection
        await mock.drop_connection(reset=False)
        await wait_for(
            lambda: not daemon.is_device_connected(mock.device_id),
            timeout=3.0,
            desc="daemon detecting disconnect",
        )
        await wait_for(lambda: len(disconnect_events) > 0, timeout=2.0)

        # 3. Verify cached report is preserved during temporary disconnect
        cached_disconnected = daemon.connectivity_plugin.get_device_report(mock.device_id)
        assert cached_disconnected is not None
        assert cached_disconnected.signal_strengths["0"].network_type == "5G"
        assert cached_disconnected.signal_strengths["0"].signal_strength == 4

        # 4. Reconnect over mTLS
        connect_events.clear()
        conn = await daemon.connect_device(mock.device_id, port=mock.bound_tcp_port)
        assert not conn.is_closed
        assert daemon.is_device_connected(mock.device_id) is True
        await wait_for(lambda: len(connect_events) > 0, timeout=2.0)

        # 5. Send updated report over new session
        await mock.send_connectivity_report({
            "0": {"networkType": "LTE", "signalStrength": 2}
        })
        def _check_lte() -> bool:
            rep = daemon.connectivity_plugin.get_device_report(mock.device_id)
            return bool(rep and "0" in rep.signal_strengths and rep.signal_strengths["0"].network_type == "LTE")

        await wait_for(
            _check_lte,
            timeout=3.0,
            desc="cache updating after reconnect",
        )

        # 6. Verify via IPC
        report = await ipc_client.get_connectivity_report(mock.device_id)
        assert report is not None
        assert report["signal_strengths"]["0"]["network_type"] == "LTE"
        assert report["signal_strengths"]["0"]["signal_strength"] == 2


async def test_e2e_cr_008_unpair_cache_cleanup(tmp_path: Path) -> None:
    """Verify unpairing a device purges its connectivity cache immediately.

    1. Mock pairs, connects, and sends report.
    2. Daemon caches report.
    3. Unpair device via IPC client.
    4. Verify connectivity report cache for device is immediately cleared.
    5. Querying unpair device via IPC confirms report is gone.
    """
    async with e2e_environment(tmp_path) as (daemon, mock, ipc_client):
        await _pair_and_connect(daemon, mock)

        # Send report
        await mock.send_connectivity_report({
            "0": {"networkType": "5G", "signalStrength": 4}
        })
        await wait_for(
            lambda: daemon.connectivity_plugin.get_device_report(mock.device_id) is not None,
            timeout=3.0,
        )

        # Unpair device via IPC
        unpair_res = await ipc_client.unpair_device(mock.device_id)
        assert unpair_res["success"] is True

        # Verify connectivity cache is purged
        await wait_for(
            lambda: daemon.connectivity_plugin.get_device_report(mock.device_id) is None,
            timeout=3.0,
            desc="connectivity cache evicted on unpair",
        )
        assert daemon.connectivity_plugin.get_device_report(mock.device_id) is None

        # Verify query on unknown device returns None or raises error
        report = await ipc_client.get_connectivity_report(mock.device_id)
        assert report is None

        # Completely unknown device raises IPCError
        with pytest.raises(IPCError) as exc_info:
            await ipc_client.get_connectivity_report("never_existed_device_xyz")
        assert "Device 'never_existed_device_xyz' is unknown" in str(exc_info.value)
